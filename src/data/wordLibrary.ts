import type { Difficulty, Word, WordCategory } from '../types'

/**
 * Word library — the pedagogical content of the game.
 *
 * ~1000 entries across 13 categories. Each word is hand-picked for
 * primary-school students. Combination sanity is enforced by the
 * `tags` / `pairTags` fields:
 *
 *  - Things carry `tags` describing what they ARE (food, fragile, gift…)
 *  - Idioms carry `pairTags` describing what they pair with
 *  - The quiz generator filters nouns whose tags don't intersect with
 *    the idiom's pairTags, so e.g. 小心翼翼 never lands next to 顯微鏡
 *
 * Canonical tag vocabulary (used in `tags` and `pairTags`):
 *   food, drink, fragile, gift, tool, toy, instrument, pet, plant,
 *   clothing, book, weather, nature, home, school, work, celebration,
 *   sport, music, art, study, surprise, anticipation, careful_action,
 *   focused, eager, joy, sadness, anger, fear, concentration,
 *   quiet_scene, busy_scene, calm_scene, natural_setting, family
 */

const make = (
  id: string,
  text: string,
  category: WordCategory,
  minLevel: Difficulty,
  hint?: string,
  tags?: string[],
  pairTags?: string[],
): Word => ({
  id,
  text,
  category,
  minLevel,
  colorToken:
    category === 'time' ? 'blue'
      : category === 'person' ? 'purple'
        : category === 'place' ? 'cyan'
          : category === 'thing' ? 'amber'
            : category === 'verb' ? 'red'
              : category === 'adjective' ? 'pink'
                : category === 'adverb' ? 'violet'
                  : category.startsWith('idiom') ? 'green'
                    : category === 'conjunction' ? 'slate'
                      : category === 'measure' ? 'lime'
                        : 'slate',
  hint,
  tags,
  pairTags,
})

